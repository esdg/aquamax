import { readFileSync, mkdirSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { Resvg } from '@resvg/resvg-js'
import { PNG } from 'pngjs'

const root = resolve(import.meta.dirname, '../..')
const names = ['thermometer', 'drop', 'three-drops', 'warning', 'thermometer-off', 'drop-off', 'three-drops-off']
const [digest, ...sizeArguments] = process.argv.slice(2)
const sizes = sizeArguments.map(Number)
if (!/^[0-9a-f]{64}$/.test(digest ?? '') || !sizes.length || sizes.some(size => !Number.isInteger(size) || size < 8 || size > 128)) {
  throw new Error('Invalid icon digest or sizes')
}

const output = [
  '// Generated by web/scripts/generate-icons.mjs. Do not edit.',
  `// source-sha256: ${digest}`,
  '#pragma once',
  '#include <cstdint>',
  '',
  'namespace aquamax::icons {',
  '',
]
for (const name of names) {
  const svg = readFileSync(resolve(root, 'assets/icons', `${name}.svg`), 'utf8')
  for (const size of sizes) {
    const png = new Resvg(svg, { fitTo: { mode: 'width', value: size } }).render().asPng()
    const image = PNG.sync.read(png)
    if (image.width !== size || image.height !== size) throw new Error(`Unexpected dimensions for ${name}`)
    const alpha = []
    for (let offset = 3; offset < image.data.length; offset += 4) alpha.push(image.data[offset])
    if (!alpha.some(value => value > 0) || !alpha.some(value => value === 0)) throw new Error(`Invalid alpha mask for ${name}`)
    const symbol = `${name.replaceAll('-', '_')}_${size}`
    output.push(`inline constexpr uint8_t ${symbol}[${size * size}] = {`)
    for (let offset = 0; offset < alpha.length; offset += 16) {
      output.push(`    ${alpha.slice(offset, offset + 16).map(value => `0x${value.toString(16).padStart(2, '0')}`).join(', ')},`)
    }
    output.push('};', '')
  }
}
const logoSvg = readFileSync(resolve(root, 'assets/logo-aquamax.svg'), 'utf8')
const logo = PNG.sync.read(new Resvg(logoSvg, { fitTo: { mode: 'width', value: 176 } }).render().asPng())
if (logo.width !== 176 || logo.height !== 43) throw new Error('Unexpected dimensions for AquaMax logo')
const logoAlpha = []
for (let offset = 3; offset < logo.data.length; offset += 4) logoAlpha.push(logo.data[offset])
if (!logoAlpha.some(value => value > 0) || !logoAlpha.some(value => value === 0)) throw new Error('Invalid AquaMax logo mask')
output.push('inline constexpr uint8_t logo_176_43[176 * 43] = {')
for (let offset = 0; offset < logoAlpha.length; offset += 16) {
  output.push(`    ${logoAlpha.slice(offset, offset + 16).map(value => `0x${value.toString(16).padStart(2, '0')}`).join(', ')},`)
}
output.push('};', '')
output.push('} // namespace aquamax::icons', '')
const destination = resolve(root, 'src/generated/icons.h')
mkdirSync(resolve(root, 'src/generated'), { recursive: true })
writeFileSync(destination, output.join('\n'))